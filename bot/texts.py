def progress_card(
    *,
    streak: int,
    total_turns: int,
    voice_minutes: float,
    wpm: float | None,
    top_error: tuple[str, int] | None,
    due_cards: int,
    level: str,
) -> str:
    lines = [
        "📊 <b>Твой прогресс</b>",
        "",
        f"Уровень: <b>{level}</b>",
        f"Серия дней подряд: <b>{streak}</b> 🔥" if streak else "Серия: пока не начата",
        f"Реплик сказано: <b>{total_turns}</b>",
        f"Наговорено: <b>{voice_minutes:.0f} мин</b>",
    ]
    if wpm:
        lines.append(f"Темп речи: <b>{wpm:.0f}</b> слов в минуту")
    if top_error:
        category, count = top_error
        lines += ["", f"Чаще всего спотыкаешься на: <b>{category}</b> ({count} раз за 2 недели)"]
    if due_cards:
        lines += ["", f"К повторению сегодня: <b>{due_cards}</b> слов → /review"]
    return "\n".join(lines)
